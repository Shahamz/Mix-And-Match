"""
Regional Prompting on PixelDiT, driven by a Mix-And-Match config file.

    python -m baselines.regional_prompting.infer_pixeldit_regional configs/template.json
    python -m baselines.regional_prompting.infer_pixeldit_regional configs/template.json --combo --runs combinations

A crop is a region of the image; a crop has tiles_per_crop tiles, interchangeable candidates meant to fit that
region. Regional Prompting places exactly one prompt per region per generation, so the k tiles of every crop come
from k separate generations that share a seed (--runs tiles, the default): run j puts tile j of every crop in its
crop. Crop i is then cut out of run j's image and saved as crop{i}/tile{j}.png.

With --runs combinations each of the k^n combinations is generated in full instead, which is k^(n-1) times the
work; the separate tiles then come from the k runs whose tile index is the same everywhere, so crop{i}/tile{j}.png
means the same thing in both modes.

The regions are the config's "crops" rectangles - this baseline needs rectangles, so it reads them whatever
"static_cropping" says - and whatever they leave uncovered becomes a background region that uses
"background_prompt". Every region is saved the way Mix-And-Match saves its crops: each tile is an RGBA image of
its region's bounding box, transparent outside the region. Crops go to crop{i}/ and the background to cropBg/.
layout.json records every region's box, so the tiles plus layout.json are enough to rebuild a full image:

    image = Image.new("RGB", (layout["width"], layout["height"]))
    for region, tile_index in zip(layout["regions"], chosen_tile_per_region):
        tile = Image.open(f"{region['folder']}/tile{tile_index}.png")
        image.paste(tile, tuple(region["box"][:2]), tile)

Only the tiles are saved by default. --combo also writes the k^n assembled combinations: in `tiles` mode they are
pasted together from the saved tiles, in `combinations` mode they are the generated images. The background region
is regenerated by every run, so it has k tiles of its own; a combination uses the background of its first crop's
run, which is what makes a combination whose indices are all equal exactly that run's image.

Everything else in the config - late_prompting, static_cropping and the rest - is Mix-And-Match's own algorithm,
not Regional Prompting, and is ignored.
"""

import argparse
import itertools
import json
import sys
from pathlib import Path

import numpy as np
import torch
from PIL import Image

from config import ConfigError, load_config
from macros import IMAGE_HEIGHT, IMAGE_WIDTH, NUM_STEPS, OUTPUT_DIR, save_image
from pipeline_mix_n_match import encode_all_prompts

from .pipeline_pixeldit_regional import RegionalPixelDiTPipeline

# ----------------------------------------------------------------------------------------------------------
# Regional Prompting knobs. They have no place in the Mix-And-Match config format, so they live here.
# ----------------------------------------------------------------------------------------------------------

# How many leading denoising steps run under regional control. After them the model runs plainly on the
# background prompt, with no mask and no base stream, which is what settles global coherence and the seams.
MASK_INJECT_STEPS = 4

# Weight of the unmasked base stream blended into the image tokens after every attention:
# x = x_regional * (1 - BASE_RATIO) + x_base * BASE_RATIO. 0 is pure regional control (sharpest regions, most
# incoherence); higher trades region separation for global coherence.
BASE_RATIO = 0.3

# A patch block is masked iff its index % this == 0; the others still run both streams, unmasked. 1 means every
# block, which is the strongest regional control.
INJECT_BLOCKS_INTERVAL = 1

# ----------------------------------------------------------------------------------------------------------

# Device the models run on.
DEVICE = "cuda"

# Folder of this baseline's results inside outputs/.
BASELINE_DIRNAME = "regional_prompting"


def read_crops(config, config_path):
    """
    Reads the rectangles this baseline puts its regions on.

    Args:
        config: MixNMatchConfig.
        config_path: path of the config file, for the error message.

    Returns:
        The first num_crops entries of the config's "crops".

    Raises:
        ConfigError: when "crops" is missing, too short, or a crop reaches outside the image.
    """
    crops = config.crops
    if not isinstance(crops, list) or len(crops) < config.num_crops:
        raise ConfigError(f'{config_path}: regional prompting places one region per crop, so "crops" must list '
                          f'at least "num_crops" ({config.num_crops}) rectangles')
    crops = crops[:config.num_crops]
    for crop in crops:
        x, y, width, height = crop["x"], crop["y"], crop["width"], crop["height"]
        if x < 0 or y < 0 or x + width > IMAGE_WIDTH or y + height > IMAGE_HEIGHT:
            raise ConfigError(f"{config_path}: crop {crop} does not fit inside the "
                              f"{IMAGE_WIDTH} x {IMAGE_HEIGHT} image")
    return crops


def build_region_masks(crops):
    """
    Turns the config's crop rectangles into the dense masks Regional Prompting works with.

    This is infer_flux_regional.py:126-146, with {x, y, width, height} converted to the corner form that loop
    expects, and a background region appended when the crops leave any pixel uncovered.

    Args:
        crops: list of {"x", "y", "width", "height"} dicts.

    Returns:
        (masks, has_background): list of [IMAGE_HEIGHT, IMAGE_WIDTH] tensors and whether the last one is a
        background region rather than a crop.
    """
    regional_masks = []
    background_mask = torch.ones((IMAGE_HEIGHT, IMAGE_WIDTH))

    for crop in crops:
        x1, y1 = crop["x"], crop["y"]
        x2, y2 = x1 + crop["width"], y1 + crop["height"]

        mask = torch.zeros((IMAGE_HEIGHT, IMAGE_WIDTH))
        mask[y1:y2, x1:x2] = 1.0

        background_mask -= mask

        regional_masks.append(mask)

    # If regional masks don't cover the whole image, append a background mask (its prompt is added with it).
    has_background = bool(background_mask.sum() > 0)
    if has_background:
        regional_masks.append(background_mask.clamp(0, 1))
    return regional_masks, has_background


def to_pil(image):
    """
    Args:
        image: [3, H, W] float tensor in [0, 1].

    Returns:
        PIL RGB image.
    """
    return Image.fromarray((image.clamp(0, 1) * 255).round().to(torch.uint8).permute(1, 2, 0).numpy())


def region_folders(num_crops, has_background):
    """
    Args:
        num_crops: number of crops from the config.
        has_background: whether a background region was appended.

    Returns:
        Folder name per region, in the order of the masks. The background region is called "cropBg", as in the
        method's own tiles folders.
    """
    return [f"crop{crop_index}" for crop_index in range(num_crops)] + (["cropBg"] if has_background else [])


def region_shapes(masks):
    """
    Finds where every region lies in pixels, the way the method does it (vis_app.crop_regions).

    A region need not be a rectangle - the background region is whatever the crops leave over - so it is
    described by its bounding box plus an alpha mask of that box. Every pixel belongs to exactly one region:
    regions are painted in order, so where crops overlap the later crop owns the pixel, and the background region
    is disjoint from all crops by construction.

    Args:
        masks: list of [IMAGE_HEIGHT, IMAGE_WIDTH] tensors, 1 inside the region.

    Returns:
        List with, per region, (box, alpha) or None when the region owns no pixel. box is the (left, top, right,
        bottom) pixel bounding box; alpha is a PIL "L" image of the box, 255 inside the region.
    """
    owner = torch.full(masks[0].shape, -1, dtype=torch.long)
    for index, mask in enumerate(masks):
        owner[mask > 0] = index

    shapes = []
    for index in range(len(masks)):
        inside = (owner == index).numpy()
        rows, cols = np.nonzero(inside)
        if len(rows) == 0:
            shapes.append(None)
            continue
        left, top, right, bottom = int(cols.min()), int(rows.min()), int(cols.max()) + 1, int(rows.max()) + 1
        alpha = Image.fromarray(inside[top:bottom, left:right].astype(np.uint8) * 255)
        shapes.append(((left, top, right, bottom), alpha))
    return shapes


def cut_tile(image, shape):
    """
    Args:
        image: PIL RGB full image.
        shape: (box, alpha) from region_shapes.

    Returns:
        PIL RGBA image of the box, transparent outside the region.
    """
    box, alpha = shape
    tile = image.crop(box).convert("RGBA")
    tile.putalpha(alpha)
    return tile


def combination_name(combination):
    """
    Args:
        combination: tile index per crop.

    Returns:
        Filename stem such as "c0-t0_c1-t1".
    """
    return "_".join(f"c{crop_index}-t{tile_index}" for crop_index, tile_index in enumerate(combination))


def save_tiles(picture, shapes, folders, tile_index, run_folder):
    """
    Cuts every region out of one generated image and saves it as that region's tile.

    Args:
        picture: PIL RGB image of the generated image.
        shapes: region_shapes output.
        folders: folder name per region.
        tile_index: which tile of every region this image holds.
        run_folder: Path of the run's output folder.

    Returns:
        The RGBA tiles in region order, so the caller can assemble combinations without reopening them (None for
        a region that owns no pixel).
    """
    tiles = []
    for shape, folder in zip(shapes, folders, strict=True):
        if shape is None:
            tiles.append(None)
            continue
        tile = cut_tile(picture, shape)
        (run_folder / folder).mkdir(parents=True, exist_ok=True)
        save_image(tile, run_folder / folder / f"tile{tile_index}.png")
        tiles.append(tile)
    return tiles


def assemble_combination(tiles, shapes):
    """
    Pastes one tile per region into a full image, through the regions' masks (vis_app.assemble_combination).

    Args:
        tiles: the chosen RGBA tile per region, in region order.
        shapes: region_shapes output.

    Returns:
        PIL RGB image.
    """
    image = Image.new("RGB", (IMAGE_WIDTH, IMAGE_HEIGHT))
    for tile, shape in zip(tiles, shapes, strict=True):
        if shape is not None:
            image.paste(tile, shape[0][:2], tile)  # the tile's alpha keeps the pixels outside its region
    return image


def choose_tiles(tiles_by_run, combination, num_crops, has_background):
    """
    Picks the tile of every region for one combination.

    Args:
        tiles_by_run: tiles_by_run[j] is save_tiles' output for run j.
        combination: tile index per crop.
        num_crops: number of crops from the config.
        has_background: whether a background region follows the crops.

    Returns:
        One RGBA tile per region, in region order. The background region, which every run produces afresh, takes
        the run of the first crop's tile, so a combination whose indices are all equal is exactly that run's image.
    """
    chosen = [tiles_by_run[tile_index][crop_index] for crop_index, tile_index in enumerate(combination)]
    if has_background:
        chosen.append(tiles_by_run[combination[0]][num_crops])
    return chosen


def write_layout(config, crops, shapes, folders, has_background, run_folder, args):
    """
    Records what the run was, next to its images.

    "regions" is what a reader needs to rebuild a full image from the tiles alone: paste every region's chosen
    tile at its box's top-left corner, using the tile's own alpha as the mask.

    Args:
        config: MixNMatchConfig.
        crops: the rectangles from read_crops.
        shapes: region_shapes output.
        folders: folder name per region.
        has_background: whether a background region follows the crops.
        run_folder: Path of the run's output folder.
        args: the parsed command line.
    """
    num_crops, num_tiles = config.num_crops, config.tiles_per_crop
    regions = []
    for index, (shape, folder) in enumerate(zip(shapes, folders, strict=True)):
        if shape is None:
            continue
        is_background = index >= num_crops
        region = {
            "folder": folder,
            "kind": "background" if is_background else "crop",
            "box": list(shape[0]),
            "tiles": num_tiles,
        }
        if is_background:
            region["prompts"] = [config.background_prompt] * num_tiles
            region["negative_prompts"] = [config.background_negative_prompt] * num_tiles
            region["note"] = ("regenerated by every run, so it has one tile per run; a combination uses the "
                              "background of its first crop's run")
        else:
            region["crop"] = crops[index]
            region["prompts"] = config.tile_prompts[index]
            region["negative_prompts"] = config.tile_negative_prompts[index]
        regions.append(region)

    layout = {
        "prefix": config.prefix,
        "width": IMAGE_WIDTH,
        "height": IMAGE_HEIGHT,
        "tiles_per_crop": num_tiles,
        "num_crops": len(regions),
        "background_crop": num_crops if has_background else None,
        "regions": regions,
        "seed": config.seed,
        "cfg_scale": config.cfg_scale,
        "num_steps": NUM_STEPS,
        "regional_prompting": {
            "mask_inject_steps": MASK_INJECT_STEPS,
            "base_ratio": BASE_RATIO,
            "inject_blocks_interval": INJECT_BLOCKS_INTERVAL,
        },
        "runs": args.runs,
        "combinations_saved": args.combo or args.runs == "combinations",
    }
    (run_folder / "layout.json").write_text(json.dumps(layout, indent=2))


def main():
    """Parses the arguments, encodes the prompts, and runs one generation per run of the config."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("config_path", type=Path, help="a config .json file")
    parser.add_argument("--combo", action="store_true",
                        help="also save the assembled combinations (default: only the separate tiles)")
    parser.add_argument("--runs", choices=("tiles", "combinations"), default="tiles",
                        help="tiles: k runs, run j uses tile j of every crop (default). "
                             "combinations: generate every one of the k^n combinations in full")
    parser.add_argument("--weights-dir", type=Path, default=None,
                        help="folder with config.json, pixeldit_t2i_v1.pth and gemma-2-2b-it/ (default: download)")
    args = parser.parse_args()

    try:
        config = load_config(args.config_path)
        crops = read_crops(config, args.config_path)
    except ConfigError as error:
        sys.exit(f"Error: invalid config: {error}")
    if args.weights_dir is not None and not args.weights_dir.is_dir():
        sys.exit(f"Error: the weights folder {args.weights_dir} does not exist")
    if not torch.cuda.is_available():
        sys.exit("Error: the baseline needs a CUDA GPU")

    num_crops, num_tiles = config.num_crops, config.tiles_per_crop
    masks, has_background = build_region_masks(crops)
    shapes = region_shapes(masks)
    folders = region_folders(num_crops, has_background)

    # Phase 1: encode every prompt the run needs, so that Gemma is gone before the transformer is loaded.
    try:
        encoded = encode_all_prompts([config], DEVICE, args.weights_dir)[0]
    except OSError as error:
        sys.exit(f"Error: could not load the weights ({error})")
    # Prompt 0 is the background prompt; prompt 1 + crop * k + tile is that tile's.
    negative_embeddings, positive_embeddings = encoded.embeddings[0], encoded.embeddings[1]

    def region_embeds(combination, embeddings):
        """Prompt features of every region for one combination, in the order `masks` is in."""
        chosen = [embeddings[1 + crop_index * num_tiles + tile_index]
                  for crop_index, tile_index in enumerate(combination)]
        if has_background:
            chosen.append(embeddings[0])
        return torch.stack(chosen)

    # Phase 2: the transformer, and one generation per run.
    try:
        pipeline = RegionalPixelDiTPipeline.from_weights(DEVICE, args.weights_dir)
    except OSError as error:
        sys.exit(f"Error: could not load the weights ({error})")

    if args.runs == "tiles":
        combinations = [(tile_index,) * num_crops for tile_index in range(num_tiles)]
    else:
        combinations = list(itertools.product(range(num_tiles), repeat=num_crops))

    run_folder = OUTPUT_DIR / BASELINE_DIRNAME / f"{config.prefix}_{num_crops}crops_{num_tiles}tiles"
    run_folder.mkdir(parents=True, exist_ok=True)
    tiles_by_run = {}
    for run_index, combination in enumerate(combinations, start=1):
        print(f"[{run_index}/{len(combinations)}] generating {combination_name(combination)}")
        image = pipeline(
            regional_embeds=region_embeds(combination, positive_embeddings),
            regional_negative_embeds=region_embeds(combination, negative_embeddings),
            base_embeds=positive_embeddings[0],
            base_negative_embeds=negative_embeddings[0],
            regional_masks=masks,
            cfg_scale=config.cfg_scale,
            seed=config.seed,
            mask_inject_steps=MASK_INJECT_STEPS,
            base_ratio=BASE_RATIO,
            inject_blocks_interval=INJECT_BLOCKS_INTERVAL,
        )
        picture = to_pil(image)
        if len(set(combination)) == 1:
            tiles_by_run[combination[0]] = save_tiles(picture, shapes, folders, combination[0], run_folder)
        if args.runs == "combinations":
            (run_folder / "combinations").mkdir(parents=True, exist_ok=True)
            save_image(picture, run_folder / "combinations" / f"{combination_name(combination)}.png")

    if args.combo and args.runs == "tiles":
        (run_folder / "combinations").mkdir(parents=True, exist_ok=True)
        for combination in itertools.product(range(num_tiles), repeat=num_crops):
            chosen = choose_tiles(tiles_by_run, combination, num_crops, has_background)
            save_image(assemble_combination(chosen, shapes),
                       run_folder / "combinations" / f"{combination_name(combination)}.png")

    write_layout(config, crops, shapes, folders, has_background, run_folder, args)
    print(f"Wrote {run_folder}")


if __name__ == "__main__":
    main()
